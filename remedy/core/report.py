"""Client and technician reports (HTML + JSON) from a saved session, with privacy redaction on by default.

Redaction replaces this PC's computer name and the signed-in user name wherever they appear (e.g. inside file
paths) and drops the client label unless the technician chooses to include it.
"""
from __future__ import annotations

import copy
import getpass
import html
import json
import platform
import time

from .utils import APP_NAME, APP_PUBLISHER, APP_VERSION

PRIVATE_TOKENS_EXTRA: list = []   # tests may add tokens


def _private_tokens() -> list:
    toks = []
    for t in (platform.node(), _user()):
        if t and len(t) >= 3:
            toks.append(t)
    return toks + PRIVATE_TOKENS_EXTRA


def _user() -> str:
    try:
        return getpass.getuser()
    except Exception:  # noqa: BLE001
        return ""


def redact_text(text: str, tokens=None) -> str:
    tokens = _private_tokens() if tokens is None else tokens
    out = str(text)
    for t in tokens:
        low = out.lower()
        tl = t.lower()
        i = low.find(tl)
        while i >= 0:
            out = out[:i] + "[redacted]" + out[i + len(t):]
            low = out.lower()
            i = low.find(tl, i + len("[redacted]"))
    return out


def redact(obj, tokens=None):
    tokens = _private_tokens() if tokens is None else tokens
    if isinstance(obj, dict):
        return {k: redact(v, tokens) for k, v in obj.items()}
    if isinstance(obj, list):
        return [redact(v, tokens) for v in obj]
    if isinstance(obj, str):
        return redact_text(obj, tokens)
    return obj


def prepare(session: dict, privacy: bool = True, include_label: bool = False) -> dict:
    data = copy.deepcopy(session)
    if not include_label:
        data.pop("client_label", None)
    data["exported"] = {"by": f"{APP_NAME} {APP_VERSION}", "at": time.strftime("%Y-%m-%d %H:%M"),
                        "privacy_redaction": bool(privacy)}
    return redact(data) if privacy else data


def to_json(session: dict, privacy: bool = True, include_label: bool = False) -> str:
    return json.dumps(prepare(session, privacy, include_label), indent=2, default=str)


