def _e(x) -> str:
    return html.escape(str(x if x is not None else ""))


def _page(title: str, body: str, data: dict) -> str:
    red = data.get("exported", {}).get("privacy_redaction")
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'><title>{_e(title)}</title>"
            f"<style>{_CSS}</style></head><body><div class='wrap'>{body}"
            f"<p class='foot'>Generated by {_e(APP_NAME)} {_e(APP_VERSION)} ({_e(APP_PUBLISHER)}) on "
            f"{_e(data.get('exported', {}).get('at'))}. "
            + ("Computer and user names are redacted. " if red else "")
            + "Measurements describe this PC at the time shown; they are not guarantees of future performance. "
              "Remedy is not a replacement for professional data backup or antivirus software.</p>"
              "</div></body></html>")


def _ts(t) -> str:
    try:
        return time.strftime("%Y-%m-%d %H:%M", time.localtime(float(t))) if t else ""
    except (TypeError, ValueError, OverflowError):
        return ""


def diagnostic_html(session: dict, privacy: bool = True) -> str:
    from .diagnostics import PROVIDER_LABEL, STATUS_LABEL
    d = prepare(session, privacy)
    dismissed = d.get("dismissed") or {}
    rows = []
    for f in d.get("findings") or []:
        dis = dismissed.get(f["id"])
        rows.append(
            f"<div class='card'><span class='tag {f['severity']}'>{_e(f['severity'].capitalize())}</span> "
            f"<span class='tag info'>{_e(STATUS_LABEL.get(f['status'], f['status']))}</span> "
            f"<b>{_e(f['title'])}</b>{' <span class=muted>(dismissed: ' + _e(dis) + ')</span>' if dis else ''}"
            f"<p>{_e(f['what'])}</p><p class='muted'><b>Why we think so:</b> {_e(f['why'])}</p>"
            + (f"<p class='muted'><b>Next steps:</b> {_e('; '.join(f['next_steps']))}</p>" if f.get('next_steps') else "")
            + "</div>")
    prov = "".join(f"<tr><td>{_e(PROVIDER_LABEL.get(k, k))}</td><td>{_e(v.get('status'))}</td>"
                   f"<td>{_e(v.get('message'))}</td></tr>" for k, v in (d.get("providers") or {}).items())
    ev = "".join(f"<tr><td>{_e(v.get('label'))}</td><td>{_e(_disp(v))}</td><td>{_e(v.get('source'))}</td>"
                 f"<td>{_e(_window(v))}</td></tr>" for v in (d.get("evidence") or {}).values())
    reps = "".join(f"<tr><td>{_e(r.get('title'))}</td><td>{_e(r.get('status'))}</td><td>{_e(r.get('summary'))}</td></tr>"
                   for r in d.get("repairs") or [])
    ver = "".join(f"<tr><td>{_e(r['action'])}</td><td>{_e(r['metric'])}</td><td>{_e(r['before'])}</td>"
                  f"<td>{_e(r['after'])}</td><td><span class='tag {'ok' if r['verdict'] == 'Verified' else 'info'}'>"
                  f"{_e(r['verdict'])}</span> {_e(r.get('note'))}</td></tr>" for r in d.get("verification") or [])
    body = (f"<div class='kicker'>Diagnostic report</div><h1>{_e('Full Diagnosis' if d.get('mode') == 'full' else 'Quick Scan')}</h1>"
            f"<p class='muted'>{_e(d.get('device', {}).get('os'))} · scanned {_e(_ts(d.get('started')))} · "
            f"result: {_e(d.get('status'))}</p>"
            f"<h2>Findings ({len(d.get('findings') or [])})</h2>" + ("".join(rows) or "<p>No problems found by the checks "
                                                                      "that ran. See 'Checks' for anything not assessed.</p>")
            + (f"<h2>Repairs</h2><table><tr><th>Action</th><th>Result</th><th>Details</th></tr>{reps}</table>" if reps else "")
            + (f"<h2>Verification</h2><table><tr><th>Repair</th><th>Measurement</th><th>Before</th><th>After</th>"
               f"<th>Verdict</th></tr>{ver}</table>" if ver else "")
            + f"<h2>Checks</h2><table><tr><th>Area</th><th>Status</th><th>Notes</th></tr>{prov}</table>"
            + f"<h2>Evidence</h2><table><tr><th>Reading</th><th>Value</th><th>Source</th><th>Window</th></tr>{ev}</table>")
    return _page("Remedy diagnostic report", body, d)


def _disp(v: dict) -> str:
    from .diagnostics import Evidence
    try:
        return Evidence(**v).display()
    except TypeError:
        return str(v.get("value"))


def _window(v: dict) -> str:
    w = v.get("window_s") or 0
    if not w:
        return "single reading"
    if w >= 86400:
        return f"last {w / 86400:.0f} days"
    return f"{w:.0f} s, {v.get('samples')} samples"


SETUP_STATUS_TEXT = {"verified": "Complete (verified)", "done": "Completed, not verified", "satisfied": "Already in place",
                     "failed": "Failed", "skipped": "Skipped", "blocked": "Blocked", "pending": "Not run",
                     "interrupted": "Interrupted", "reboot": "Requires restart", "manual_done": "Checked by technician",
                     "manual_open": "Not checked"}


def setup_html(session: dict, privacy: bool = True, include_label: bool = False) -> str:
    d = prepare(session, privacy, include_label)
    tasks = d.get("tasks") or {}
    rows = []
    for t in tasks.values():
        st = t.get("status", "pending")
        cls = "ok" if st in ("verified", "satisfied", "manual_done") else "bad" if st in ("failed", "blocked") else "info"
        rows.append(f"<tr><td>{_e(t.get('title'))}</td><td>{_e(t.get('kind'))}</td><td><span class='tag {cls}'>"
                    f"{_e(SETUP_STATUS_TEXT.get(st, st))}</span></td><td>{_e(t.get('detail'))}</td></tr>")
    facts = "".join(f"<tr><td>{_e(f.get('label'))}</td><td>{_e(f.get('value'))}</td><td>{_e(f.get('state'))}</td></tr>"
                    for f in (d.get("inspection") or []))
    counts = {}
    for t in tasks.values():
        counts[t.get("status")] = counts.get(t.get("status"), 0) + 1
    summary = " · ".join(f"{n} {SETUP_STATUS_TEXT.get(k, k).lower()}" for k, n in sorted(counts.items()) if k)
    reboot = any(t.get("reboot") and t.get("status") in ("done", "verified") for t in tasks.values())
    note = d.get("note") or ""
    label = d.get("client_label") or ""
    body = (f"<div class='kicker'>New PC setup · handoff report</div><h1>{_e(label or 'Your PC is ready')}</h1>"
            f"<p class='muted'>Profile: {_e(d.get('profile', {}).get('name'))} (v{_e(d.get('profile', {}).get('version'))}) · "
            f"{_e(d.get('setup_type', '').replace('_', ' '))} · finished {_e(_ts(d.get('updated')))}</p>"
            f"<div class='card'><b>Summary:</b> {_e(summary or 'nothing was run')}"
            + ("<br><b>Restart needed:</b> some changes finish after the next restart." if reboot else "")
            + "</div>"
            + (f"<h2>Technician note</h2><div class='card'>{_e(note)}</div>" if note else "")
            + f"<h2>What was done</h2><table><tr><th>Item</th><th>Type</th><th>Result</th><th>Details</th></tr>"
            f"{''.join(rows)}</table>"
            + (f"<h2>This PC</h2><table><tr><th>Item</th><th>Value</th><th>How we know</th></tr>{facts}</table>" if facts else "")
            + "<h2>Recommended next steps</h2><ul><li>Restart once so every change takes effect.</li>"
              "<li>Sign in to your browser and cloud storage yourself; Remedy never handles passwords.</li>"
              "<li>Keep Windows Update and Microsoft Defender switched on.</li>"
              "<li>Back up important files regularly (OneDrive, an external drive, or both).</li></ul>")
    return _page("Remedy setup report", body, d)
